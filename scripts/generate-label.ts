// Renders the label every photo try-on carries ("Ön izleme · renk ve desen
// gerçeğinden farklı olabilir", Showroom package job 5) once, in Inter, as a
// PNG embedded in lib/giydirme/etiket-png.ts. At run time the server only lays
// this picture over the result: no font is needed on the server.
//
//   npx tsx scripts/generate-label.ts

import { writeFileSync } from "node:fs";
import sharp from "sharp";

export const LABEL_TEXT = "Ön izleme · renk ve desen gerçeğinden farklı olabilir";

async function main() {
  const w = 1800;
  const h = 96;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">
    <rect x="0" y="0" width="${w}" height="${h}" rx="22" fill="#1d1d1b" fill-opacity="0.78"/>
    <text x="40" y="63" font-family="Inter" font-weight="600" font-size="46" fill="#ffffff">${LABEL_TEXT}</text>
  </svg>`;
  // trim the strip to the text's own width
  const raw = await sharp(Buffer.from(svg)).png().toBuffer();
  const { data, info } = await sharp(raw).raw().toBuffer({ resolveWithObject: true });
  let right = 0;
  for (let x = info.width - 1; x >= 0 && !right; x--) for (let y = 0; y < info.height; y++) if (data[(y * info.width + x) * 4] > 200 && data[(y * info.width + x) * 4 + 3] > 200) { right = x; break; }
  const width = Math.min(w, right + 40);
  const svg2 = svg.replace(`width="${w}" height="${h}">`, `width="${width}" height="${h}">`).replace(`width="${w}" height="${h}" rx`, `width="${width}" height="${h}" rx`);
  const png = await sharp(Buffer.from(svg2)).png({ compressionLevel: 9 }).toBuffer();
  writeFileSync(
    "lib/giydirme/etiket-png.ts",
    `// Generated by scripts/generate-label.ts: the try-on label as a PNG (${width} × ${h} px). Do not edit.\nexport const LABEL_PNG_BASE64 = "${png.toString("base64")}";\nexport const LABEL_SIZE = { width: ${width}, height: ${h} } as const;\n`,
  );
  writeFileSync(process.env.ONIZLEME ?? "/dev/null", png);
  console.log(`etiket ${width} × ${h}, ${png.length} bayt`);
}

void main();
