// Renders the labels the try-on pictures carry once, in Inter, as PNGs
// embedded in lib/giydirme/etiket-png.ts. At run time the server only lays
// the picture over the result: no font is needed on the server.
//  - job 5 (the customer's sofa): "Ön izleme · renk ve desen gerçeğinden farklı olabilir"
//  - job 15 (the customer's room): "Ön izleme · ölçüler yaklaşıktır"
//
//   npx tsx scripts/generate-label.ts

import { writeFileSync } from "node:fs";
import sharp from "sharp";

export const LABEL_TEXT = "Ön izleme · renk ve desen gerçeğinden farklı olabilir";
export const SALON_LABEL_TEXT = "Ön izleme · ölçüler yaklaşıktır, ürün yerleşimi temsilîdir";

async function render(text: string): Promise<{ png: Buffer; width: number; height: number }> {
  const w = 1800;
  const h = 96;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">
    <rect x="0" y="0" width="${w}" height="${h}" rx="22" fill="#1d1d1b" fill-opacity="0.78"/>
    <text x="40" y="63" font-family="Inter" font-weight="600" font-size="46" fill="#ffffff">${text}</text>
  </svg>`;
  // trim the strip to the text's own width
  const raw = await sharp(Buffer.from(svg)).png().toBuffer();
  const { data, info } = await sharp(raw).raw().toBuffer({ resolveWithObject: true });
  let right = 0;
  for (let x = info.width - 1; x >= 0 && !right; x--) for (let y = 0; y < info.height; y++) if (data[(y * info.width + x) * 4] > 200 && data[(y * info.width + x) * 4 + 3] > 200) { right = x; break; }
  const width = Math.min(w, right + 40);
  const svg2 = svg.replace(`width="${w}" height="${h}">`, `width="${width}" height="${h}">`).replace(`width="${w}" height="${h}" rx`, `width="${width}" height="${h}" rx`);
  return { png: await sharp(Buffer.from(svg2)).png({ compressionLevel: 9 }).toBuffer(), width, height: h };
}

async function main() {
  const a = await render(LABEL_TEXT);
  const b = await render(SALON_LABEL_TEXT);
  writeFileSync(
    "lib/giydirme/etiket-png.ts",
    `// Generated by scripts/generate-label.ts: the try-on labels as PNGs. Do not edit.\n` +
      `export const LABEL_PNG_BASE64 = "${a.png.toString("base64")}";\nexport const LABEL_SIZE = { width: ${a.width}, height: ${a.height} } as const;\n` +
      `export const SALON_LABEL_PNG_BASE64 = "${b.png.toString("base64")}";\nexport const SALON_LABEL_SIZE = { width: ${b.width}, height: ${b.height} } as const;\n`,
  );
  console.log(`etiketler ${a.width} × ${a.height}, ${b.width} × ${b.height}`);
}

void main();
